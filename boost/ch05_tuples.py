# ══════════════════════════════════════════════════════════
# 第 1 部分：逗号才是元组 —— 四种"意外"现场
# ══════════════════════════════════════════════════════════

# 1.1 括号不是元组的标志
t1 = 1, 2, 3                     # 不写括号，照样是元组
print(type(t1).__name__)         # tuple

# 1.2 单元素必须带逗号（最高频笔误）
not_tuple = (42)                 # 只是数字 42 加了括号，用于运算优先级
real_tuple = (42,)
print(type(not_tuple).__name__)  # int
print(type(real_tuple).__name__) # tuple
# 记法：括号是装饰，逗号才是灵魂

# 1.3 return 的裸逗号 → 打包成元组（ch04/ch05 的知识点）
def give_two():
    return 1, 2                  # 等价于 return (1, 2)

result = give_two()
print(type(result).__name__)     # tuple —— 不管你写不写括号

# 1.4 所以"函数返回多个值"是假象：其实是返回一个元组
one = give_two()                 # 用一个变量接
print(one)                       # (1, 2)
x, y = give_two()                # 用解包接（见第 2 部分）
print(x, y)                      # 1 2


# ══════════════════════════════════════════════════════════
# 第 2 部分：解包 —— 元组最常用的姿势
# ══════════════════════════════════════════════════════════

# 2.1 基础：逗号对逗号，数量必须相等
a, b = 10, 20
print(a, b)                      # 10 20

# 2.2 经典应用：一行交换两个变量（右边先打包，左边再拆包）
a, b = b, a
print(a, b)                      # 20 10

# 2.3 数量不等会怎样
try:
    a, b = 1, 2, 3
except ValueError as e:
    print("报错:", e)             # too many values to unpack (expected 2)

# 2.4 星号口袋：接收剩余所有，装进【列表】（注意不是元组！）
first, *rest = (1, 2, 3, 4)
print(first, rest, type(rest).__name__)   # 1 [2, 3, 4] list

# 2.5 星号可以在中间（ch05 练习 3 swap_ends 的原理）
first, *mid, last = (1, 2, 3, 4)
print(first, mid, last)          # 1 [2, 3] 4

# 2.6 return 里星号摊开 + 逗号重新打包：
#     mid 一度是列表，但 return 的逗号决定了产物是元组
def swap_ends(t):
    first, *mid, last = t
    return last, *mid, first     # *mid 摊开 → 逗号打包 → 元组

r = swap_ends((1, 2, 3, 4))
print(r, type(r).__name__)       # (4, 2, 3, 1) tuple

# 2.7 想返回列表？显式用方括号打包
def swap_ends_list(t):
    first, *mid, last = t
    return [last, *mid, first]

r2 = swap_ends_list((1, 2, 3, 4))
print(r2, type(r2).__name__)     # [4, 2, 3, 1] list
# 规律：容器类型由"打包方"决定 —— return 逗号=元组，[]=列表


# ══════════════════════════════════════════════════════════
# 第 3 部分：不可变性 —— 能做什么、不能做什么
# ══════════════════════════════════════════════════════════

t = (1, 2, 2, 3)

# 3.1 所有"只读"操作都行：索引、切片、in、len、count、index
print(t[0], t[1:3], 2 in t, len(t))   # 1 (2, 2) True 4
print(t.count(2), t.index(3))         # 2 3

# 3.2 所有"修改"操作都不行
try:
    t[0] = 99
except TypeError as e:
    print("报错:", e)             # 'tuple' object does not support item assignment

# 3.3 没有 append / remove / sort —— 想改？造新的
more = t + (4,)                   # 拼接产新元组，t 不变
print(more, t)                    # (1, 2, 2, 3, 4) (1, 2, 2, 3)

# 3.4 "不可变"的精确含义：元素指向不能换，元素本身可能可变
inner = [1, 2]
weird = (inner, "x")              # 元组里装了一个列表
weird[0].append(3)                # ✅ 合法！改的是列表的内容，不是元组的指向
print(weird)                      # ([1, 2, 3], 'x')
# weird[0] = [9]                  # ❌ 这才是改指向，才被禁止


# ══════════════════════════════════════════════════════════
# 第 4 部分：不可变带来的特权 —— 能当字典的键、能进集合
# ══════════════════════════════════════════════════════════

# 4.1 字典的键必须"可哈希"（本质不可变）：元组可以，列表不行
grid = {(0, 0): "起点", (3, 4): "终点"}
print(grid[(3, 4)])              # 终点 —— 坐标键的天然选择

try:
    bad = {[0, 0]: "x"}
except TypeError as e:
    print("报错:", e)             # unhashable type: 'list'

# 4.2 集合同理
points = {(0, 0), (1, 1), (0, 0)}  # 重复的坐标自动去重
print(len(points))               # 2


# ══════════════════════════════════════════════════════════
# 第 5 部分：元组 vs 列表 —— 选择标准
# ══════════════════════════════════════════════════════════

# 列表：内容会长会短会改 —— 购物车、待办、消息历史
todo = ["买菜", "写代码"]
todo.append("复习元组")

# 元组：固定搭配的一组值 —— 坐标、RGB 颜色、(键, 值) 对、函数多返回值
color = (255, 140, 0)            # RGB 不会增删，天生的元组
for k, v in {"数学": 90}.items():
    print(k, v)                  # items() 给的每一项就是元组 ("数学", 90)

# 快速互转
print(tuple([1, 2, 3]))          # (1, 2, 3)
print(list((4, 5)))              # [4, 5]


